"""Validates es.json / fr.json against en_catalog.json and generates GameTextCatalog.cs.

Rejected translations (missing, empty, placeholder or edge-whitespace mismatch) are left out, so that text stays
English at runtime; they are listed for fixing.
"""
import json
import pathlib
import re
import sys

SP = pathlib.Path(sys.argv[1])
OUT = pathlib.Path(sys.argv[2])
PLACEHOLDER = re.compile(r"(?<!\{)\{\d+(?:,[^}:]*)?(?::[^}]*)?\}")

en = json.loads((SP / "en_catalog.json").read_text(encoding="utf-8"))


def edges(s):
    return s[: len(s) - len(s.lstrip())], s[len(s.rstrip()):]


def check(source, target):
    if not isinstance(target, str) or not target.strip():
        return "missing or empty"
    if sorted(PLACEHOLDER.findall(source)) != sorted(PLACEHOLDER.findall(target)):
        return "placeholders differ"
    if source.count("{{") != target.count("{{") or source.count("}}") != target.count("}}"):
        return "escaped braces differ"
    if edges(source) != edges(target):
        return "leading/trailing whitespace differs"
    return None


def load(code):
    path = SP / (code + ".json")
    data = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {"exact": {}, "formats": {}}
    extra_path = SP / ("extra_" + code + ".json")
    if extra_path.exists():
        extra = json.loads(extra_path.read_text(encoding="utf-8"))
        for kind in ("exact", "formats"):
            data.setdefault(kind, {}).update(extra.get(kind, {}))
    result = {}
    problems = []
    for kind in ("exact", "formats"):
        pairs = []
        table = data.get(kind, {})
        for source in en[kind]:
            target = table.get(source)
            problem = check(source, target)
            if problem:
                problems.append((kind, source, problem))
                continue
            pairs.append((source, target))
        result[kind] = pairs
    return result, problems


def cs(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 32:
            out.append("\\u%04x" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def array(name, pairs):
    lines = [f"        internal static readonly string[] {name} =", "        {"]
    for source, target in pairs:
        lines.append(f"            {cs(source)}, {cs(target)},")
    lines.append("        };")
    return "\n".join(lines)


blocks = []
report = {}
for code, title in (("es", "Spanish"), ("fr", "French")):
    tables, problems = load(code)
    report[code] = problems
    blocks.append(array(title + "Exact", tables["exact"]))
    blocks.append(array(title + "Formats", tables["formats"]))
    print(f"{code}: exact {len(tables['exact'])}/{len(en['exact'])}, formats {len(tables['formats'])}/{len(en['formats'])}, rejected {len(problems)}")
    for kind, source, problem in problems[:15]:
        print(f"   REJECTED {kind}: {problem}: {source!r}")

body = "\n\n".join(blocks)
OUT.write_text(
    "namespace OutOfReach.Localization\n{\n"
    "    /// <summary>\n"
    "    /// GENERATED by the LANG-01 tooling from the English strings of the Core, Simulation, Inventory and Interaction\n"
    "    /// sources and their reviewed Spanish and French translations. Pairs: English, translation. Do not edit by hand.\n"
    "    /// </summary>\n"
    "    internal static class GameTextCatalog\n    {\n" + body + "\n    }\n}\n",
    encoding="utf-8", newline="\n")
print("wrote", OUT)
